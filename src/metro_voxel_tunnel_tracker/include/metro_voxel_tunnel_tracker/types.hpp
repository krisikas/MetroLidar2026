#pragma once

#include <cstdint>
#include <vector>

namespace metro_voxel_tunnel_tracker
{

/**
 * @brief 3D-точка лидара в декартовой системе координат сенсора
 */
struct Point3D
{
  float x{0.0f};          ///< Поперечная координата: вправо (+), влево (-) относительно оси лидара (м)
  float y{0.0f};          ///< Продольная координата: вперед (-) по ходу движения поезда (м)
  float z{0.0f};          ///< Вертикальная координата: вверх (+), вниз (-) относительно лидара (м)
  float intensity{0.0f};  ///< Интенсивность / отражательная способность луча
};

/**
 * @brief Семантическая классификация вокселя
 */
enum class VoxelType : uint8_t
{
  UNCLASSIFIED = 0,
  GROUND_BED,         ///< Балластная призма / водоотводной лоток / полотно
  RAIL_HEAD,          ///< Рельсовая нить (возвышение над полотном в створе 1520 мм)
  WALL_LEFT,          ///< Левая граница / стена тоннеля
  WALL_RIGHT,         ///< Правая граница / стена тоннеля
  CEILING,            ///< Свод / перекрытие тоннеля
  OBSTACLE            ///< Нарушение габарита подвижного состава (препятствие)
};

/**
 * @brief Элементарный 3D-воксель пространства
 */
struct Voxel
{
  int32_t ix{0};              ///< Дискретный индекс по X
  int32_t iy{0};              ///< Дискретный индекс по Y
  int32_t iz{0};              ///< Дискретный индекс по Z
  float x{0.0f};              ///< Центроид X (м)
  float y{0.0f};              ///< Центроид Y (м)
  float z{0.0f};              ///< Центроид Z (м)
  float min_z{0.0f};          ///< Минимальная высота точек в вокселе (м)
  float max_z{0.0f};          ///< Максимальная высота точек в вокселе (м)
  float mean_intensity{0.0f}; ///< Средняя интенсивность
  uint16_t point_count{0};    ///< Число сырых точек в данном вокселе
  VoxelType type{VoxelType::UNCLASSIFIED};
};

/**
 * @brief Опорная точка 3D-траектории пути и габаритных границ тоннеля
 */
struct TrackWaypoint
{
  float x{0.0f};              ///< Латеральная координата центра ходовой колеи (м)
  float y{0.0f};              ///< Продольное удаление сечения от поезда (м)
  float z_rail{0.0f};         ///< Расчетный уровень головки рельса (УГР) в системе координат лидара (м)
  float yaw{0.0f};            ///< Угол рыскания касательной траектории к оси движения (рад)
  float pitch{0.0f};          ///< Угол тангажа продольного уклона траектории пути (рад)
  float left_boundary{-2.2f}; ///< Левая габаритная граница тоннеля/препятствий на данном срезе (м)
  float right_boundary{2.2f}; ///< Правая габаритная граница тоннеля/препятствий на данном срезе (м)
  float ceiling_z{2.8f};       ///< Оценка высоты свода тоннеля над УГР на данном срезе (м)
  float confidence{1.0f};     ///< Коэффициент доверия к измерениям на данном срезе (0.0 - 1.0)
  bool valid{false};          ///< Флаг достоверности геометрического детектирования на срезе
};

/**
 * @brief Кластер вокселей препятствия внутри габарита подвижного состава
 */
struct ObstacleCluster
{
  float center_x{0.0f};       ///< Центроид препятствия X (м)
  float center_y{0.0f};       ///< Центроид препятствия Y (м)
  float center_z{0.0f};       ///< Центроид препятствия Z (м)
  float size_x{0.0f};         ///< Габарит по ширине (м)
  float size_y{0.0f};         ///< Габарит по длине (м)
  float size_z{0.0f};         ///< Габарит по высоте (м)
  float distance{0.0f};       ///< Дистанция от поезда вдоль траектории пути (м)
  size_t voxel_count{0};      ///< Количество вокселей в кластере
  size_t total_points{0};     ///< Общее число точек лидара в препятствии
};

}  // namespace metro_voxel_tunnel_tracker
